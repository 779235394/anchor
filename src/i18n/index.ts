export type Dict = (typeof DICT)['zh'];

export function getDict(lang: Lang) {
  return DICT[lang];
}

export function taskStatusLabel(status: TaskStatus, lang: Lang): string {
  const t = DICT[lang];
  switch (status) {
    case 'todo':
      return t.statusTodo;
    case 'doing':
      return t.statusDoing;
    case 'confirm':
      return t.statusConfirm;
    case 'done':
      return t.statusDone;
  }
}
